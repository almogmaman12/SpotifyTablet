/**
 * Port of kuroshiro 1.2.0's `toRawRomaji` with its Hepburn table (util.js), which is what Spicy
 * Lyrics' romaji goes through. Kana (and full-width digits and signs) become romaji; anything
 * else passes through. Hepburn's extras: n' before a vowel or y (kin'en), doubled consonants for
 * っ (kitto, matcha), m before b/m/p (shimbun), and macrons for ー (tōkyō).
 */
object KanaRomanizer {

    fun romanize(text: String): String {
        val str = HATSU.replace(text) { "${it.value}'" }
        val result = StringBuilder(str.length * 2)
        var pnt = 0
        while (pnt < str.length) {
            val two = if (pnt + 2 <= str.length) HEPBURN[str.substring(pnt, pnt + 2)] else null
            if (two != null) {
                result.append(two)
                pnt += 2
            } else {
                val one = str.substring(pnt, pnt + 1)
                result.append(HEPBURN[one] ?: one)
                pnt += 1
            }
        }
        var out = TSU.replace(result) { m -> m.groupValues[2] + m.groupValues[2] }
        out = out.replace("cc", "tc")
        out = out.replace(Regex("[っッ]"), "tsu")
        out = out.replace("nm", "mm").replace("nb", "mb").replace("np", "mp")
        return out.replace("aー", "ā").replace("iー", "ī").replace("uー", "ū").replace("eー", "ē").replace("oー", "ō")
    }

